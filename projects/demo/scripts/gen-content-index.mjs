#!/usr/bin/env node
// Generates lib/generated/content.ts so pages import every content/schema/*.json and
// content/faq/*.json statically. BusinessOS may add files to those folders; this keeps
// the build working without code edits and without runtime fs access (Workers-safe).
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const list = (dir) =>
  readdirSync(join(root, dir))
    .filter((f) => f.endsWith(".json"))
    .sort();
const ident = (prefix, f) => prefix + f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_");

const schema = list("content/schema");
const faq = list("content/faq");
const lines = [
  "// AUTO-GENERATED by scripts/gen-content-index.mjs — do not edit.",
  ...schema.map((f) => `import ${ident("schema_", f)} from "@/content/schema/${f}";`),
  ...faq.map((f) => `import ${ident("faq_", f)} from "@/content/faq/${f}";`),
  "",
  `export const schemaFiles: Record<string, unknown> = { ${schema.map((f) => `"${f}": ${ident("schema_", f)}`).join(", ")} };`,
  `export const faqFiles: Record<string, unknown> = { ${faq.map((f) => `"${f}": ${ident("faq_", f)}`).join(", ")} };`,
  "",
];
mkdirSync(join(root, "lib/generated"), { recursive: true });
writeFileSync(join(root, "lib/generated/content.ts"), lines.join("\n"));
console.log(`content index: ${schema.length} schema, ${faq.length} faq`);
